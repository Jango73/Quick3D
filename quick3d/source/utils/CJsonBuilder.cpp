
// Application
#include "CJsonBuilder.h"

//-------------------------------------------------------------------------------------------------

/***************************************************************************/
/*!
    Joins pre-rendered JSON values into an array document.
*/
/***************************************************************************/
QString CJsonBuilder::joinArray(const QStringList& vItems)
{
    return QString("[%1]").arg(vItems.join(","));
}

//-------------------------------------------------------------------------------------------------

/***************************************************************************/
/*!
    Returns the success envelope with no payload.
*/
/***************************************************************************/
QString CJsonBuilder::okResponse()
{
    return QString("{\"ok\":true}");
}

//-------------------------------------------------------------------------------------------------

/***************************************************************************/
/*!
    Returns the failure envelope.
*/
/***************************************************************************/
QString CJsonBuilder::errorResponse(const QString& sError)
{
    return QString("{\"ok\":false,\"error\":\"%1\"}").arg(sError);
}

//-------------------------------------------------------------------------------------------------

/***************************************************************************/
/*!
    Returns the failure envelope from a literal.
*/
/***************************************************************************/
QString CJsonBuilder::errorResponse(const char* pError)
{
    return errorResponse(QString(pError));
}
